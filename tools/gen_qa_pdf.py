"""
生成组会答辩准备手册 PDF
"""
from reportlab.pdfgen import canvas
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import cm
import os
from datetime import datetime

output = r'C:\Users\34612\Desktop\组会答辩准备手册.pdf'

c = canvas.Canvas(output, pagesize=A4)
W, H = A4

# ===== 工具函数 =====
y = H - 2*cm
page = 1

def new_page():
    global y, page
    c.showPage()
    page += 1
    y = H - 2*cm
    c.setFont("Helvetica-Bold", 16)
    c.drawString(2*cm, y, f"组会答辩准备手册（续） 第{page}页")
    y -= 1.2*cm

def title(text):
    global y
    if y < 4*cm:
        new_page()
    c.setFont("Helvetica-Bold", 16)
    c.drawString(2*cm, y, text)
    y -= 0.8*cm

def subtitle(text):
    global y
    if y < 3*cm:
        new_page()
    c.setFont("Helvetica-Bold", 12)
    c.drawString(2*cm, y, text)
    y -= 0.6*cm

def body(text):
    global y
    if y < 2*cm:
        new_page()
    c.setFont("Helvetica", 10)
    # wrap long lines
    words = text
    c.drawString(2.5*cm, y, words[:120])
    if len(words) > 120:
        y -= 0.45*cm
        c.drawString(2.5*cm, y, words[120:240])
        if len(words) > 240:
            y -= 0.45*cm
            c.drawString(2.5*cm, y, words[240:])
    y -= 0.55*cm

def qa(q, a):
    global y
    if y < 3*cm:
        new_page()
    c.setFont("Helvetica-Bold", 10)
    c.drawString(2*cm, y, f"Q: {q}")
    y -= 0.45*cm
    c.setFont("Helvetica", 10)
    c.drawString(2.5*cm, y, f"A: {a[:115]}")
    if len(a) > 115:
        y -= 0.45*cm
        c.drawString(2.5*cm, y, f"   {a[115:230]}")
        if len(a) > 230:
            y -= 0.45*cm
            c.drawString(2.5*cm, y, f"   {a[230:345]}")
            if len(a) > 345:
                y -= 0.45*cm
                c.drawString(2.5*cm, y, f"   {a[345:]}")
    y -= 0.7*cm

# ===== 封面 =====
c.setFont("Helvetica-Bold", 24)
c.drawCentredString(W/2, H/2+3*cm, "组会答辩准备手册")
c.setFont("Helvetica", 14)
c.drawCentredString(W/2, H/2+1.5*cm, "Python依赖漏洞智能研判系统")
c.setFont("Helvetica", 11)
c.drawCentredString(W/2, H/2, f"汇报日期：{datetime.now().strftime('%Y年%m月%d日')}")
c.drawCentredString(W/2, H/2-1*cm, "包含：汇报话术 + 常见问题 + 应答策略")
c.drawCentredString(W/2, H/2-2*cm, "使用说明：汇报前看一遍，被问到翻对应问题")

new_page()

