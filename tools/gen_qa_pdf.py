# ===== 第二部分：被问到的技术问题 =====
title("二、技术相关常见问题")

qa("这个工具是怎么工作的？从上传到出结果，每一步都在做什么？",
   "第一步解析依赖文件，提取出包名和版本号。第二步拿包名和版本号去四个公开数据库查漏洞——OSV查有没有漏洞，NVD查CVSS分数，GitHub查修复版本，EPSS查利用概率。第三步交叉验证，三个数据库信息拼在一起，给置信度评级。第四步综合CVSS、EPSS、置信度计算出修复优先级。第五步生成报告和图表。")

qa("什么是交叉验证？怎么做的？",
   "同一个漏洞去三个数据库查。比如CVE-2021-35042，OSV说有并给了9.8分，NVD也说有给了9.8分，GitHub也说有给了修复版本3.2.2。三方都确认，而且分数差在2分以内，就标记为交叉验证通过、置信度高。如果只有一个数据库说了、或者给的分数差异很大，就标低置信度。相当于多找几个医生会诊，不是说一个医生说了就信。")

qa("OSV、NVD、GitHub Advisory分别是什么？",
   "OSV是Google维护的开源漏洞数据库，你告诉它包名和版本号，它告诉你有没有漏洞。NVD是美国政府的国家漏洞数据库，最权威，给出CVSS分数和漏洞描述。GitHub Advisory是GitHub的安全公告，告诉你怎么修、修到哪个版本。三个都是免费公开的API。")

qa("EPSS是什么？为什么用这个？",
   "EPSS是FIRST组织做的漏洞利用预测评分。CVSS告诉你漏洞多严重，但严重不一定有人用。EPSS告诉你这个漏洞未来30天被实际利用的概率有多大。比如一个CVSS 9.8的漏洞，EPSS只有1%，说明虽然严重但基本没人在攻击。反过来CVSS 5.0但EPSS 50%，反而更需要关注。")

qa("修复优先级是怎么算出来的？",
   "三个维度加权打分。CVSS严重度占60%，EPSS利用概率占30%，置信度占10%。算出一个综合分，8分以上立即修复，6-8分尽快修复，4-6分计划修复，2-4分关注即可，2分以下低优先。CVSS权重最大因为漏洞本身严重程度是最重要的参考。")

qa("图表是怎么画出来的？",
   "Streamlit框架自带的图表功能。把数据整理成DataFrame表格，传给st.bar_chart()或st.scatter_chart()，自动出图。不需要额外安装matplotlib之类的东西。就像Excel里选中数据点插入图表一样。")

qa("依赖解析遇到版本区间是怎么处理的？",
   "比如requirements.txt里写的是>=2.0,<3.0，解析器会把操作符去掉，取第一个合法版本号2.0，然后用这个版本号去查询。如果写的是==3.2.1就直接用3.2.1。只是提取数字部分，不做复杂的版本范围匹配。")

qa("NVD有时候为什么会查不到数据？",
   "三种情况：一是漏洞太新，CVE编号刚分配，NVD还没录入（NVD更新比OSV慢）；二是有些漏洞只存在于GitHub Advisory或OSV里，NVD没收录；三是网络超时，NVD服务器在国外有时请求失败。正因如此才需要多源交叉验证——一个查不到还有另外两个。")

new_page()

