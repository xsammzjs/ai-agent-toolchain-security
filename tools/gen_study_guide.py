# ============ 工具函数 ============
def h1(text):
    doc.add_heading(text, level=1)

def h2(text):
    doc.add_heading(text, level=2)

def h3(text):
    doc.add_heading(text, level=3)

def body(text, bold=False, color=None, indent=0):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    r = p.add_run(text)
    r.font.bold = bold
    if color:
        r.font.color.rgb = RGBColor(*color)
    return p

def bullet(text, bold=False):
    p = doc.add_paragraph(text, style='List Bullet')
    if bold:
        for r in p.runs:
            r.font.bold = True
    return p

def code_block(text):
    """等宽字体代码块"""
    for line in text.split('\n'):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.6)
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.15
        r = p.add_run(line if line else ' ')
        r.font.name = 'Consolas'
        r._element.rPr.rFonts.set(qn('w:eastAsia'), 'Microsoft YaHei')
        r.font.size = Pt(9)
        r.font.color.rgb = RGBColor(0x33, 0x33, 0x33)

def make_table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers), style='Light Grid Accent 1')
    for i, htext in enumerate(headers):
        t.rows[0].cells[i].text = htext
        for p in t.rows[0].cells[i].paragraphs:
            for r in p.runs:
                r.font.bold = True
                r.font.size = Pt(9.5)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = str(val)
            for p in cells[i].paragraphs:
                for r in p.runs:
                    r.font.size = Pt(9.5)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph('')
    return t

def tip_box(text):
    """浅色提示框段落"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.3)
    r = p.add_run('💡 ' + text)
    r.font.size = Pt(9.5)
    r.font.color.rgb = RGBColor(0x8a, 0x5a, 0x00)
    return p

